P_GLOBAL = float(os.environ.get("P_GLOBAL", "0.0005"))
P_DISCORD = float(os.environ.get("P_DISCORD", "0.0003"))
P_SHADOWS = float(os.environ.get("P_SHADOWS", "0.0002"))

