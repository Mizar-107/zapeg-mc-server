SERVANT_OBJECTIVE = "zapeg_hsvc"
SERVANT_SCORE_HOLDER = "#total"
SERVANT_WORLD_OBJECTIVE = "zh_svc_world"
SERVANT_WORLD_HOLDER = "#world"
PLAYER_NAME_RE = re.compile(r"^[A-Za-z0-9_]{1,16}$")

